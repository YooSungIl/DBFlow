    DB_CONFIG_ID INTEGER NOT NULL,
    TABLE_NAME TEXT NOT NULL,
    TABLE_COMMENT TEXT,
    TABLE_TYPE TEXT NOT NULL,
    OWNER_NAME TEXT NOT NULL,
    TABLE_DELETED_YN INTEGER NOT NULL DEFAULT 0,
