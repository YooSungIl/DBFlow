    COLUMN_ORDER INTEGER NOT NULL,
    DATA_TYPE TEXT NOT NULL,
    DATA_LENGTH INTEGER,
    DATA_SCALE INTEGER,
    NULLABLE_YN INTEGER NOT NULL,
    DEFAULT_VALUE TEXT,
    IDENTITY_YN INTEGER,
    IDENTITY_TYPE TEXT,
    FOREIGN KEY (HISTORY_TABLE_ID) REFERENCES DBF_HISTORY_TABLE_SNAPSHOT (HISTORY_TABLE_ID),
    CHECK (NULLABLE_YN IN (0, 1)),
    CHECK (IDENTITY_YN IS NULL OR IDENTITY_YN IN (0, 1)),
    CHECK (IDENTITY_TYPE IS NULL OR IDENTITY_TYPE IN ('ALWAYS', 'BY_DEFAULT'))
);

CREATE TABLE DBF_HISTORY_INDEX_SNAPSHOT
(
