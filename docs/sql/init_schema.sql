    FOREIGN KEY (DB_CONFIG_ID) REFERENCES DBF_DB_CONFIG (DB_CONFIG_ID),
    CHECK (TABLE_TYPE IN ('TABLE', 'VIEW'))
);

CREATE TABLE DBF_CURRENT_COLUMN_SNAPSHOT
(
    CURRENT_COLUMN_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CURRENT_TABLE_ID INTEGER NOT NULL,
    COLUMN_NAME TEXT NOT NULL,
    COLUMN_COMMENT TEXT,
    COLUMN_ORDER INTEGER NOT NULL,
    DATA_TYPE TEXT NOT NULL,
    DATA_LENGTH INTEGER,
    DATA_SCALE INTEGER,
    NULLABLE_YN INTEGER NOT NULL,
    DEFAULT_VALUE TEXT,
    IDENTITY_YN INTEGER,
    IDENTITY_TYPE TEXT,
    FOREIGN KEY (CURRENT_TABLE_ID) REFERENCES DBF_CURRENT_TABLE_SNAPSHOT (CURRENT_TABLE_ID),
    CHECK (NULLABLE_YN IN (0, 1)),
    CHECK (IDENTITY_YN IS NULL OR IDENTITY_YN IN (0, 1)),
    CHECK (IDENTITY_TYPE IS NULL OR IDENTITY_TYPE IN ('ALWAYS', 'BY_DEFAULT'))
);

CREATE TABLE DBF_CURRENT_INDEX_SNAPSHOT
(
    CURRENT_INDEX_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CURRENT_TABLE_ID INTEGER NOT NULL,
    INDEX_NAME TEXT NOT NULL,
    INDEX_COMMENT TEXT,
    INDEX_TYPE TEXT NOT NULL DEFAULT 'BTREE',
    INDEX_COLUMNS TEXT NOT NULL,
    UNIQUE_YN INTEGER NOT NULL,
    FOREIGN KEY (CURRENT_TABLE_ID) REFERENCES DBF_CURRENT_TABLE_SNAPSHOT (CURRENT_TABLE_ID),
    CHECK (INDEX_TYPE IN ('BTREE', 'HASH', 'GIN', 'GIST', 'SPGIST', 'BRIN')),
    CHECK (UNIQUE_YN IN (0, 1))
);

/*
 * 6. DBFlow 커밋했던 이력 오브젝트 테이블(이력 오브젝트들)
 * 커밋 시 반드시 해당 테이블들에다가 데이터를 남겨야한다.
